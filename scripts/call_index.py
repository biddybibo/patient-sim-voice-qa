"""Write CALLS.md: one row per call with scenario, persona, length, end reason, how natural our bot
was (src/analysis/bot_review.py) and the most severe clinic finding (src/analysis/evaluate.py).

Run:  uv run python scripts/call_index.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.config import CALLS_DIR  # noqa: E402

SEVERITY = ["critical", "high", "medium", "low"]
BOT = {"natural": "natural", "minor_issues": "minor issues", "noticeable_issues": "**noticeable issues**"}


def main() -> None:
    reviews_path = CALLS_DIR / "_analysis" / "bot_review.json"
    reviews = json.loads(reviews_path.read_text()) if reviews_path.exists() else {}
    rows = [
        "# Call index",
        "",
        "Every call in `calls/` (generated by `scripts/call_index.py`). **Bot** is how natural our patient bot sounded "
        "(automated review of its turns, `src/analysis/bot_review.py`). Calls up to 029 predate most bot fixes; "
        "030 onward use the improved bot (see ITERATION_LOG.md). **Top clinic finding** is the most severe "
        "*unverified* candidate from the evaluator; confirmed bugs are in BUG_REPORT.md.",
        "",
        "| Call | Scenario | Persona | Length | Ended | Bot | Top clinic finding |",
        "|---|---|---|---|---|---|---|",
    ]
    for d in sorted(p for p in CALLS_DIR.iterdir() if p.is_dir() and p.name[:3].isdigit()):
        meta = json.loads((d / "transcript.json").read_text())
        metrics = json.loads((d / "metrics.json").read_text())
        dur = metrics.get("duration_s") or 0
        top = "—"
        if (d / "findings.json").exists():
            findings = json.loads((d / "findings.json").read_text())["findings"]
            if findings:
                f = min(findings, key=lambda x: SEVERITY.index(x["severity"]))
                top = f"{f['severity']}: {f['title']} ({f['timestamp']})"
        bot = BOT.get(reviews.get(d.name, {}).get("overall"), "—")
        rows.append(
            f"| [{d.name[:3]}](calls/{d.name}/) | {meta.get('scenario') or 'hello-world'} | "
            f"{meta.get('persona') or '—'} | {int(dur // 60)}:{int(dur % 60):02d} | {metrics['end_reason']} | "
            f"{bot} | {top.replace('|', '/')} |"
        )
    (CALLS_DIR.parent / "CALLS.md").write_text("\n".join(rows) + "\n")
    print(f"wrote CALLS.md ({len(rows) - 6} calls)")


if __name__ == "__main__":
    main()
